use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use clap::{Arg, ArgMatches, Command};
use infusdk::util::infu::InfuResult;
use infusdk::util::uid::{is_uid, uid_chars};
use rpassword::prompt_password;

use crate::storage::object::filename as object_filename;
use crate::util::crypto::{decrypt_file_data, encrypt_file_data};
use crate::util::fs::expand_tilde;

/// If this many files in a row fail to decrypt before any succeeds, the old key is almost certainly wrong.
const MAX_FAILURES_BEFORE_FIRST_SUCCESS: usize = 5;

pub fn make_clap_subcommand() -> Command {
  Command::new("rekey")
    .about(concat!(
      "Re-encrypt a user's object files in a local object store with a new object encryption key, writing them to ",
      "another data directory. The source files are never modified. The keys are prompted for, without echo. ",
      "The item database is not read or changed: objectEncryptionKey in the user's user.json must be updated separately."
    ))
    .arg(
      Arg::new("user_id")
        .long("user-id")
        .help("The id of the user whose files are re-encrypted.")
        .num_args(1)
        .required(true),
    )
    .arg(
      Arg::new("src")
        .long("src")
        .help("Data directory holding the files to re-encrypt (in <src>/user_<id>/files/).")
        .num_args(1)
        .required(true),
    )
    .arg(
      Arg::new("dest")
        .long("dest")
        .help(concat!(
          "Data directory to write the re-encrypted files to (in <dest>/user_<id>/files/). Created if it does not ",
          "exist. Files already present are skipped, so an interrupted run can be repeated."
        ))
        .num_args(1)
        .required(true),
    )
}

pub fn execute(sub_matches: &ArgMatches) -> InfuResult<()> {
  let user_id = sub_matches.get_one::<String>("user_id").unwrap();
  if !is_uid(user_id) {
    return Err(format!("'{}' is not a valid user id.", user_id).into());
  }
  let src_files_dir = user_files_dir(sub_matches.get_one::<String>("src").unwrap(), user_id)?;
  let dest_files_dir = user_files_dir(sub_matches.get_one::<String>("dest").unwrap(), user_id)?;
  if !src_files_dir.is_dir() {
    return Err(format!("Source files directory {:?} does not exist.", src_files_dir).into());
  }

  println!("User:        {}", user_id);
  println!("Source:      {}", src_files_dir.display());
  println!("Destination: {}\n", dest_files_dir.display());

  let old_key = prompt_key("Current (old) object encryption key: ")?;
  let new_key = prompt_key("New object encryption key: ")?;
  if prompt_key("New object encryption key (again): ")? != new_key {
    return Err("The two entries of the new key do not match.".into());
  }
  if old_key == new_key {
    return Err("The new key is the same as the old key.".into());
  }

  let summary = rekey_files(user_id, &src_files_dir, &dest_files_dir, &old_key, &new_key)?;

  println!(
    "\nRe-encrypted: {}. Already in destination (skipped): {}. Failed: {}.",
    summary.written,
    summary.skipped,
    summary.failures.len()
  );
  if !summary.failures.is_empty() {
    println!("Failures:");
    for failure in &summary.failures {
      println!("  {}", failure);
    }
    return Err(format!("{} file(s) could not be re-encrypted (listed above).", summary.failures.len()).into());
  }
  println!("Remember to set objectEncryptionKey in user.json to the new key.");
  Ok(())
}

fn user_files_dir(data_dir: &str, user_id: &str) -> InfuResult<PathBuf> {
  let mut path = expand_tilde(data_dir).ok_or(format!("Data path '{}' is not valid.", data_dir))?;
  path.push(format!("user_{}", user_id));
  path.push("files");
  Ok(path)
}

fn prompt_key(prompt: &str) -> InfuResult<String> {
  let key = prompt_password(prompt).map_err(|e| format!("Could not read key: {}", e))?.trim().to_lowercase();
  // Checked here because decode_hex panics on input of odd length.
  if key.len() != 64 || !key.chars().all(|c| c.is_ascii_hexdigit()) {
    return Err("A key must be 64 hex characters (as generated by 'infumap keygen').".into());
  }
  Ok(key)
}

struct RekeySummary {
  written: usize,
  skipped: usize,
  failures: Vec<String>,
}

fn rekey_files(
  user_id: &str,
  src_files_dir: &Path,
  dest_files_dir: &Path,
  old_key: &str,
  new_key: &str,
) -> InfuResult<RekeySummary> {
  fs::create_dir_all(dest_files_dir)?;
  if fs::canonicalize(src_files_dir)? == fs::canonicalize(dest_files_dir)? {
    return Err("Source and destination are the same directory.".into());
  }

  // Outside files/, so a file left part written by an interrupted run is never mistaken for an object.
  let tmp_dir = dest_files_dir.parent().ok_or("Destination has no parent directory.")?.join("rekey_tmp");
  fs::create_dir_all(&tmp_dir)?;

  let mut failures = vec![];
  let mut to_process = vec![];
  for i in uid_chars() {
    for j in uid_chars() {
      let subdir = format!("{}{}", i, j);
      let src_subdir = src_files_dir.join(&subdir);
      if !src_subdir.is_dir() {
        return Err(format!("Source directory {:?} is missing. Is this a local object store?", src_subdir).into());
      }
      // All 256 are created up front because the local object store fails to list a files directory without them.
      fs::create_dir_all(dest_files_dir.join(&subdir))?;
      let mut names = vec![];
      for entry in fs::read_dir(&src_subdir)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if !entry.file_type()?.is_file() || !is_uid(&name) {
          failures.push(format!("{}/{}: unexpected entry, not processed.", subdir, name));
          continue;
        }
        names.push(name);
      }
      names.sort();
      to_process.extend(names.into_iter().map(|name| (subdir.clone(), name)));
    }
  }

  let total = to_process.len();
  let mut written = 0;
  let mut skipped = 0;
  let mut attempt_failures = 0;
  for (n, (subdir, item_id)) in to_process.iter().enumerate() {
    let dest_path = dest_files_dir.join(subdir).join(item_id);
    // Destination files are only created by renaming a complete, verified file into place, so any that exists is done.
    if dest_path.exists() {
      skipped += 1;
      continue;
    }
    let src_path = src_files_dir.join(subdir).join(item_id);
    let tmp_path = tmp_dir.join(item_id);
    let aad = object_filename(&user_id.to_owned(), item_id);
    match rekey_file(&src_path, &dest_path, &tmp_path, &aad, old_key, new_key) {
      Ok(num_bytes) => {
        written += 1;
        println!("Re-encrypted {}/{}: {} [{} bytes]", n + 1, total, item_id, num_bytes);
      }
      Err(e) => {
        println!("FAILED {}/{}: {}: {}", n + 1, total, item_id, e);
        failures.push(format!("{}/{}: {}", subdir, item_id, e));
        attempt_failures += 1;
        if written == 0 && attempt_failures >= MAX_FAILURES_BEFORE_FIRST_SUCCESS {
          return Err(
            format!(
              "The first {} files attempted all failed, with none succeeding. The old key is probably wrong.",
              attempt_failures
            )
            .into(),
          );
        }
      }
    }
  }

  // Only empty if every file succeeded. Otherwise leftovers are overwritten by the next run.
  let _ = fs::remove_dir(&tmp_dir);

  Ok(RekeySummary { written, skipped, failures })
}

fn rekey_file(
  src_path: &Path,
  dest_path: &Path,
  tmp_path: &Path,
  aad: &str,
  old_key: &str,
  new_key: &str,
) -> InfuResult<usize> {
  let ciphertext = fs::read(src_path)?;
  let plaintext = decrypt_file_data(old_key, &ciphertext, aad)?;
  let new_ciphertext = encrypt_file_data(new_key, &plaintext, aad)?;
  // Cheap next to the disk I/O, and this rewritten copy is about to become the only one.
  if decrypt_file_data(new_key, &new_ciphertext, aad)? != plaintext {
    return Err("Re-encrypted data does not decrypt back to the original.".into());
  }
  let mut file = fs::File::create(tmp_path)?;
  file.write_all(&new_ciphertext)?;
  file.sync_all()?;
  drop(file);
  fs::rename(tmp_path, dest_path)?;
  Ok(plaintext.len())
}

#[cfg(test)]
mod tests {
  use super::*;
  use crate::util::crypto::generate_key;
  use infusdk::util::uid::new_uid;

  struct TempDir(PathBuf);

  impl Drop for TempDir {
    fn drop(&mut self) {
      let _ = fs::remove_dir_all(&self.0);
    }
  }

  fn temp_dir() -> TempDir {
    let path = std::env::temp_dir().join(format!("infumap-rekey-test-{}", new_uid()));
    fs::create_dir_all(&path).unwrap();
    TempDir(path)
  }

  fn make_src(root: &Path, user_id: &str, key: &str, contents: &[&[u8]]) -> (PathBuf, Vec<(String, Vec<u8>)>) {
    let files_dir = root.join("src").join(format!("user_{}", user_id)).join("files");
    for i in uid_chars() {
      for j in uid_chars() {
        fs::create_dir_all(files_dir.join(format!("{}{}", i, j))).unwrap();
      }
    }
    let mut items = vec![];
    for content in contents {
      let item_id = new_uid();
      let encrypted = encrypt_file_data(key, content, &object_filename(&user_id.to_owned(), &item_id)).unwrap();
      fs::write(files_dir.join(&item_id[..2]).join(&item_id), encrypted).unwrap();
      items.push((item_id, content.to_vec()));
    }
    (files_dir, items)
  }

  #[test]
  fn rekeys_all_files_and_skips_them_on_rerun() {
    let tmp = temp_dir();
    let user_id = new_uid();
    let (old_key, new_key) = (generate_key(), generate_key());
    let (src_files_dir, items) = make_src(&tmp.0, &user_id, &old_key, &[b"one", b"two", b""]);
    let dest_files_dir = tmp.0.join("dest").join(format!("user_{}", user_id)).join("files");
    let src_before: Vec<Vec<u8>> =
      items.iter().map(|(id, _)| fs::read(src_files_dir.join(&id[..2]).join(id)).unwrap()).collect();

    let summary = rekey_files(&user_id, &src_files_dir, &dest_files_dir, &old_key, &new_key).unwrap();
    assert_eq!((summary.written, summary.skipped, summary.failures.len()), (3, 0, 0));
    for (n, (item_id, content)) in items.iter().enumerate() {
      let aad = object_filename(&user_id, item_id);
      let rekeyed = fs::read(dest_files_dir.join(&item_id[..2]).join(item_id)).unwrap();
      assert_eq!(&decrypt_file_data(&new_key, &rekeyed, &aad).unwrap(), content);
      assert!(decrypt_file_data(&old_key, &rekeyed, &aad).is_err());
      assert_eq!(fs::read(src_files_dir.join(&item_id[..2]).join(item_id)).unwrap(), src_before[n]);
    }
    assert_eq!(fs::read_dir(&dest_files_dir).unwrap().count(), 256);
    assert!(!dest_files_dir.parent().unwrap().join("rekey_tmp").exists());

    let summary = rekey_files(&user_id, &src_files_dir, &dest_files_dir, &old_key, &new_key).unwrap();
    assert_eq!((summary.written, summary.skipped, summary.failures.len()), (0, 3, 0));
  }

  #[test]
  fn reports_a_corrupt_file_and_continues() {
    let tmp = temp_dir();
    let user_id = new_uid();
    let (old_key, new_key) = (generate_key(), generate_key());
    let (src_files_dir, items) = make_src(&tmp.0, &user_id, &old_key, &[b"one", b"two", b"three"]);
    let corrupt_id = &items[1].0;
    let corrupt_path = src_files_dir.join(&corrupt_id[..2]).join(corrupt_id);
    let mut bytes = fs::read(&corrupt_path).unwrap();
    *bytes.last_mut().unwrap() ^= 1;
    fs::write(&corrupt_path, bytes).unwrap();
    let dest_files_dir = tmp.0.join("dest").join(format!("user_{}", user_id)).join("files");

    let summary = rekey_files(&user_id, &src_files_dir, &dest_files_dir, &old_key, &new_key).unwrap();
    assert_eq!((summary.written, summary.failures.len()), (2, 1));
    assert!(summary.failures[0].contains(corrupt_id.as_str()));
    assert!(!dest_files_dir.join(&corrupt_id[..2]).join(corrupt_id).exists());
  }

  #[test]
  fn aborts_when_the_old_key_is_wrong() {
    let tmp = temp_dir();
    let user_id = new_uid();
    let (old_key, new_key) = (generate_key(), generate_key());
    let contents: Vec<&[u8]> = vec![b"x"; MAX_FAILURES_BEFORE_FIRST_SUCCESS + 2];
    let (src_files_dir, _) = make_src(&tmp.0, &user_id, &old_key, &contents);
    let dest_files_dir = tmp.0.join("dest").join(format!("user_{}", user_id)).join("files");

    let result = rekey_files(&user_id, &src_files_dir, &dest_files_dir, &generate_key(), &new_key);
    assert!(result.is_err());
  }

  #[test]
  fn refuses_to_write_into_the_source() {
    let tmp = temp_dir();
    let user_id = new_uid();
    let (old_key, new_key) = (generate_key(), generate_key());
    let (src_files_dir, _) = make_src(&tmp.0, &user_id, &old_key, &[b"one"]);

    assert!(rekey_files(&user_id, &src_files_dir, &src_files_dir, &old_key, &new_key).is_err());
  }
}
